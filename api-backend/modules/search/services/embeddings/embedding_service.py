"""
Service for generating text embeddings using sentence-transformers.
Supports multilingual texts including Russian.
"""

from typing import List, Union
import numpy as np
from sentence_transformers import SentenceTransformer


class EmbeddingService:
    """
    Singleton service for generating text embeddings.
    Uses paraphrase-multilingual-MiniLM-L12-v2 model which supports
    50+ languages including Russian and generates 384-dimensional vectors.
    """

    _instance = None
    _model = None

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super().__new__(cls)
        return cls._instance

    def __init__(self):
        if self._model is None:
            # Load the multilingual model (384 dimensions)
            # This model supports Russian and many other languages
            self._model = SentenceTransformer(
                "paraphrase-multilingual-MiniLM-L12-v2"
            )

    def generate_embedding(self, text: str) -> np.ndarray:
        """
        Generate embedding vector for a single text.

        Args:
            text: Input text to encode

        Returns:
            numpy array of shape (384,)
        """
        if not text or not text.strip():
            # Return zero vector for empty text
            return np.zeros(384, dtype=np.float32)

        # Truncate text if too long (model has 128 token limit)
        # Approximately 500 characters for Russian text
        max_chars = 500
        if len(text) > max_chars:
            text = text[:max_chars]

        embedding = self._model.encode(text, convert_to_numpy=True)
        return embedding.astype(np.float32)

    def generate_embeddings(
        self, texts: List[str], batch_size: int = 32
    ) -> List[np.ndarray]:
        """
        Generate embedding vectors for multiple texts in batches.

        Args:
            texts: List of input texts to encode
            batch_size: Number of texts to process in one batch

        Returns:
            List of numpy arrays, each of shape (384,)
        """
        if not texts:
            return []

        # Truncate long texts
        max_chars = 500
        processed_texts = [
            text[:max_chars] if text and len(text) > max_chars else (text or "")
            for text in texts
        ]

        # Generate embeddings in batches for efficiency
        embeddings = self._model.encode(
            processed_texts,
            batch_size=batch_size,
            convert_to_numpy=True,
            show_progress_bar=True,
        )

        return [emb.astype(np.float32) for emb in embeddings]

    def get_dimension(self) -> int:
        """Get the dimension of embeddings generated by this service."""
        return 384


# Global singleton instance
embedding_service = EmbeddingService()
